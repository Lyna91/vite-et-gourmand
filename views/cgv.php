<h1>Conditions générales de vente</h1>

<p>Vite &amp; Gourmand est une entreprise fictive (projet ECF Studi).</p>
<h2>1. Objet</h2>
<p>Les présentes CGV encadrent les commandes de menus passées sur le site de Vite &amp; Gourmand, traiteur situé 3 rue Notre-Dame, 33000 Bordeaux. Toute commande vaut acceptation des CGV.</p>
<h2>2. Commande</h2>
<ul>
    <li>Pour commander, le client doit avoir un compte et être connecté.</li>
    <li>Chaque menu indique un nombre minimum de personnes, un prix par personne et ses conditions (par exemple un délai de commande). Le client les lit sur la fiche du menu avant de commander.</li>
    <li>Les menus sont disponibles dans la limite du stock affiché.</li>
    <li>Avant de valider, le client voit le détail du prix. Il reçoit un e-mail de confirmation après la commande.</li>
</ul>

<h2>3. Prix et remise</h2>
<ul>
    <li>Les prix sont indiqués en euros TTC, par personne.</li>
    <li>Remise de 10 % si la commande compte au moins 5 personnes de plus que le minimum du menu.</li>
</ul>
<h2>4. Livraison</h2>
<ul>
    <li>À Bordeaux : livraison gratuite.</li>
    <li>En dehors de Bordeaux : 5 € + 0,59 € par kilomètre, selon la distance indiquée par le client.</li>
    <li>Le client indique l'adresse, la date, l'heure et le lieu de la prestation.</li>
</ul>
<h2>5. Paiement</h2>
<p>Sur facture, paiement lors de la livraison sur place</p>
<p>Lors d'un prêt de matériel, si restitution après le délai, paiement par chèque à l'adresse de l'entreprise à l'ordre du "comptable vite et gourmand"</p>
<h2>6. Modification et annulation</h2>
<ul>
    <li>Tant que la commande n'est pas acceptée par Vite &amp; Gourmand, le client peut la modifier (sauf le menu choisi) ou l'annuler depuis son espace.</li>
    <li>Une fois la commande acceptée, toute modification ou annulation passe par Vite &amp; Gourmand, qui contacte le client par téléphone ou par e-mail et en indique le motif.</li>
</ul>
<h2>7. Droit de rétractation</h2>
<p>Le droit de rétractation de 14 jours ne s'applique pas : les menus sont des denrées qui se détériorent rapidement, et la prestation est fournie à une date fixée (article L221-28 du Code de la consommation).</p>
<h2>8. Matériel prêté</h2>
<ul>
    <li>Le matériel prêté avec la commande doit être rendu dans un délai de 10 jours ouvrés après la prestation. Le client en est informé par e-mail.</li>
    <li>Passé ce délai, des frais de 600 € sont facturés.</li>
</ul>
<h2>9. Suivi et avis</h2>
<p>Le client suit l'état de sa commande dans son espace. Quand la commande est terminée, il peut laisser un avis (note de 1 à 5 et commentaire), publié après validation par Vite & Gourmand.</p>
<h2>10. Litiges</h2>
<p>Les CGV sont soumises au droit français. En cas de litige, le client contacte d'abord Vite &amp; Gourmand pour trouver une solution amiable. Il peut ensuite recourir gratuitement à un médiateur de la consommation (fictif dans le cadre de ce projet).</p>

